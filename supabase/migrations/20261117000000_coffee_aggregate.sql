CREATE TABLE IF NOT EXISTS public.coffee_ingredients (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE CHECK (BTRIM(name) <> ''),
  unit TEXT NOT NULL CHECK (unit IN ('gr', 'ml'))
);

CREATE TABLE IF NOT EXISTS public.coffee_menus (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE CHECK (BTRIM(name) <> ''),
  is_sub_recipe BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS public.coffee_menu_recipes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  menu_id BIGINT NOT NULL
    REFERENCES public.coffee_menus(id) ON DELETE CASCADE,
  ingredient_id BIGINT NOT NULL
    REFERENCES public.coffee_ingredients(id) ON DELETE RESTRICT,
  amount NUMERIC(12, 4) NOT NULL CHECK (amount > 0),
  UNIQUE (menu_id, ingredient_id)
);

CREATE INDEX IF NOT EXISTS idx_coffee_menu_recipes_menu_id
  ON public.coffee_menu_recipes (menu_id);

ALTER TABLE public.coffee_ingredients ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.coffee_menus ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.coffee_menu_recipes ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "public read coffee ingredients"
  ON public.coffee_ingredients;
